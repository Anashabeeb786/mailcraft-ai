/**
 * models/db.js — SQLite Database Layer
 *npm
 * Uses `better-sqlite3` for synchronous, file-based SQLite access.
 * Exports:
 *  - initDB()    : Creates tables if they don't exist (called on server start)
 *  - getDB()     : Returns the singleton DB instance for use in controllers
 */
const fs = require("fs");
const Database = require("better-sqlite3");
const path = require("path");

// Store the DB file in the /data directory (auto-created if needed)
const DB_PATH = path.join(__dirname, "../data/mailcraft.db");

// Singleton instance — opened once, shared across all controllers
let db;

/**
 * initDB
 * Called once at server startup. Creates tables if they don't already exist.
 * Uses IF NOT EXISTS so it's safe to call multiple times.
 */
function initDB() {
  const dataDir = path.dirname(DB_PATH);

if (!fs.existsSync(dataDir)) {
  fs.mkdirSync(dataDir, { recursive: true });
}
 db = new Database(DB_PATH);

  // Enable WAL mode for better read concurrency
  db.pragma("journal_mode = WAL");
  // Enforce foreign key constraints (SQLite has them off by default)
  db.pragma("foreign_keys = ON");

  // ── Users Table ──────────────────────────────────────────
  db.exec(`
    CREATE TABLE IF NOT EXISTS users (
      id            INTEGER PRIMARY KEY AUTOINCREMENT,
      name          TEXT    NOT NULL,
      email         TEXT    UNIQUE NOT NULL,
      password_hash TEXT    NOT NULL,
      created_at    DATETIME DEFAULT CURRENT_TIMESTAMP
    )
  `);

  // ── Emails Table ─────────────────────────────────────────
  // Stores every email generated by each user for history retrieval
  db.exec(`
    CREATE TABLE IF NOT EXISTS emails (
      id                INTEGER PRIMARY KEY AUTOINCREMENT,
      user_id           INTEGER NOT NULL,
      purpose           TEXT    NOT NULL,
      recipient_name    TEXT    NOT NULL,
      recipient_context TEXT    NOT NULL,
      tone              TEXT    NOT NULL,
      extra_context     TEXT    DEFAULT '',
      subject           TEXT    NOT NULL,
      body              TEXT    NOT NULL,
      created_at        DATETIME DEFAULT CURRENT_TIMESTAMP,
      FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
    )
  `);

  console.log("✅ Database initialized at:", DB_PATH);
  return db;
}

/**
 * getDB
 * Returns the active database instance.
 * Throws if initDB() hasn't been called yet.
 */
function getDB() {
  if (!db) {
    throw new Error("Database not initialized. Call initDB() first.");
  }
  return db;
}

module.exports = { initDB, getDB };
