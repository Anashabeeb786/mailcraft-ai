/**
 * utils/pdfExport.js — Client-Side PDF Export
 *
 * Uses jsPDF to generate a professionally formatted PDF of a generated email.
 * Runs entirely in the browser — no server needed.
 *
 * Interview talking point:
 *   jsPDF draws directly to a canvas/PDF spec. We use addText with manual
 *   word-wrapping (splitTextToSize) to handle long bodies gracefully.
 */

import jsPDF from 'jspdf'

/**
 * exportEmailAsPDF
 * Generates and downloads a PDF of the given email object.
 *
 * @param {{ subject: string, body: string, tone?: string, purpose?: string }} email
 */
export function exportEmailAsPDF(email) {
  const doc = new jsPDF({
    orientation: 'portrait',
    unit: 'mm',
    format: 'a4',
  })

  const PAGE_WIDTH  = doc.internal.pageSize.getWidth()
  const PAGE_HEIGHT = doc.internal.pageSize.getHeight()
  const MARGIN      = 20
  const TEXT_WIDTH  = PAGE_WIDTH - MARGIN * 2
  let y = MARGIN

  // ── Header Background ──────────────────────────────────────────────────
  doc.setFillColor(99, 102, 241) // Indigo
  doc.rect(0, 0, PAGE_WIDTH, 18, 'F')

  // ── Brand Name ─────────────────────────────────────────────────────────
  doc.setFont('helvetica', 'bold')
  doc.setFontSize(11)
  doc.setTextColor(255, 255, 255)
  doc.text('MailCraft AI', MARGIN, 12)

  // ── Subtitle ───────────────────────────────────────────────────────────
  doc.setFontSize(7)
  doc.setFont('helvetica', 'normal')
  doc.text('AI-Powered Professional Email Generator', MARGIN, 16.5)

  // Generated date — right aligned
  const dateStr = new Date().toLocaleDateString('en-IN', {
    day: 'numeric', month: 'long', year: 'numeric'
  })
  doc.text(dateStr, PAGE_WIDTH - MARGIN, 12, { align: 'right' })

  y = 26

  // ── Email Metadata ─────────────────────────────────────────────────────
  doc.setFillColor(245, 247, 255)
  doc.roundedRect(MARGIN, y, TEXT_WIDTH, email.tone ? 22 : 12, 3, 3, 'F')

  doc.setTextColor(80, 80, 120)
  doc.setFontSize(7.5)
  doc.setFont('helvetica', 'normal')

  if (email.purpose) {
    doc.text(`Purpose: ${email.purpose}`, MARGIN + 4, y + 5)
  }
  if (email.tone) {
    doc.text(`Tone: ${email.tone}`, MARGIN + 4, y + 11)
  }
  if (email.recipient_name) {
    doc.text(`To: ${email.recipient_name}${email.recipient_context ? ` · ${email.recipient_context}` : ''}`, MARGIN + 4, y + 17)
  }

  y += email.tone ? 28 : 18

  // ── Subject Line ───────────────────────────────────────────────────────
  doc.setTextColor(30, 30, 60)
  doc.setFontSize(8)
  doc.setFont('helvetica', 'bold')
  doc.text('SUBJECT', MARGIN, y)

  y += 5

  doc.setFontSize(13)
  doc.setFont('helvetica', 'bold')
  doc.setTextColor(40, 40, 90)

  const subjectLines = doc.splitTextToSize(email.subject, TEXT_WIDTH)
  doc.text(subjectLines, MARGIN, y)
  y += subjectLines.length * 7 + 5

  // Divider
  doc.setDrawColor(200, 200, 230)
  doc.line(MARGIN, y, PAGE_WIDTH - MARGIN, y)
  y += 8

  // ── Email Body ─────────────────────────────────────────────────────────
  doc.setFontSize(8)
  doc.setFont('helvetica', 'bold')
  doc.setTextColor(30, 30, 60)
  doc.text('EMAIL BODY', MARGIN, y)
  y += 6

  doc.setFont('helvetica', 'normal')
  doc.setFontSize(10.5)
  doc.setTextColor(40, 40, 40)

  const bodyLines = doc.splitTextToSize(email.body, TEXT_WIDTH)

  // Auto-paginate: if lines overflow the page, add a new page
  for (const line of bodyLines) {
    if (y > PAGE_HEIGHT - MARGIN) {
      doc.addPage()
      y = MARGIN
    }
    doc.text(line, MARGIN, y)
    y += 6
  }

  // ── Footer ─────────────────────────────────────────────────────────────
  doc.setFontSize(7)
  doc.setTextColor(160, 160, 180)
  doc.text('Generated by MailCraft AI · For professional use', PAGE_WIDTH / 2, PAGE_HEIGHT - 8, { align: 'center' })

  // ── Save ───────────────────────────────────────────────────────────────
  let safeName = 'email'
  if (email && email.subject && typeof email.subject === 'string') {
    safeName = email.subject.replace(/[^a-z0-9]/gi, '_').toLowerCase().slice(0, 30)
  }
  const filename = `mailcraft_${safeName}.pdf`
  
  // Use the native jsPDF save method
  doc.save(filename)
}
